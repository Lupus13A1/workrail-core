/**
 * Image helpers — shared fallback for avatars / logos / any image field.
 * When no image is provided, a DiceBear "initials" avatar URL is used instead.
 * Docs: https://www.dicebear.com/styles/initials/
 */

const DICEBEAR_BASE_URL = 'https://api.dicebear.com/9.x/initials';
const DEFAULT_SEED = 'User';

export type DicebearFormat = 'svg' | 'png' | 'jpg' | 'webp' | 'avif';

export interface InitialsAvatarOptions {
  /** Output format (default `svg`). PNG/JPG are capped at 256px by DiceBear. */
  format?: DicebearFormat;
  /** Size in px (1–256 for raster formats). */
  size?: number;
  /** Corner radius 0–50 (50 = circle). */
  radius?: number;
  /** Background hex colors without `#`, e.g. ['b6e3f4', 'c0aede']. DiceBear picks one from the seed. */
  backgroundColor?: string[];
  /** Text color hex without `#`. */
  textColor?: string[];
  /** Number of initials, 1 or 2 (default 2). */
  chars?: 1 | 2;
}

/** `true` when the value is null / undefined / not a string / empty or whitespace only. */
export function isBlankImage(image: unknown): image is null | undefined | '' {
  return typeof image !== 'string' || image.trim().length === 0;
}

/** Picks the first non-blank candidate as the avatar seed, e.g. `buildAvatarSeed(fullName, email)`. */
export function buildAvatarSeed(...candidates: Array<string | null | undefined>): string {
  return candidates.find((c) => typeof c === 'string' && c.trim())?.trim() ?? DEFAULT_SEED;
}

/** Builds a DiceBear "initials" avatar URL for the given seed (e.g. "Thanet Chankhua" → "TC"). */
export function getInitialsAvatarUrl(seed?: string | null, options: InitialsAvatarOptions = {}): string {
  const { format = 'svg', size, radius, backgroundColor, textColor, chars } = options;
  const params = new URLSearchParams({ seed: buildAvatarSeed(seed) });
  if (size !== undefined) params.set('size', String(size));
  if (radius !== undefined) params.set('radius', String(radius));
  if (backgroundColor?.length) params.set('backgroundColor', backgroundColor.join(','));
  if (textColor?.length) params.set('textColor', textColor.join(','));
  if (chars !== undefined) params.set('chars', String(chars));
  return `${DICEBEAR_BASE_URL}/${format}?${params.toString()}`;
}

/**
 * Returns the given image (trimmed) or, when it is missing/blank, a DiceBear initials avatar.
 * @example resolveImage(dto.photoURL, user.fullName)
 */
export function resolveImage(
  image: string | null | undefined,
  seed?: string | null,
  options?: InitialsAvatarOptions,
): string {
  return isBlankImage(image) ? getInitialsAvatarUrl(seed, options) : image.trim();
}

/** `true` when the URL is a DiceBear initials avatar generated by this helper (useful to regenerate on rename). */
export function isDefaultInitialsAvatar(image: string | null | undefined): boolean {
  return !isBlankImage(image) && image.startsWith(DICEBEAR_BASE_URL);
}
